// Lightweight, dependency-free i18n for ADAR Front Desk.
//
// Scope note: full on-screen translation is provided for English, Spanish,
// Bangla, and Hindi. Arabic (ar-XA) is offered as a *voice* language only
// (Google's STT/TTS handle it natively -- see useVoiceChat.ts) because
// rendering it well needs right-to-left layout this app doesn't implement
// yet; picking Arabic keeps the on-screen UI in English and says so in the
// language picker, rather than shipping a half-mirrored layout.
export type LangCode = 'en-US' | 'es-US' | 'bn-BD' | 'hi-IN' | 'ar-XA';

export interface LanguageOption {
  code: LangCode;
  label: string;
  /** Set on languages whose on-screen text isn't translated yet (voice only). */
  voiceOnly?: boolean;
}

